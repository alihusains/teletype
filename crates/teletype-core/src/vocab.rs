//! Vocabulary packs: curated domain term lists (canonical spelling -> known
//! mis-hearings) that the ASR-mishearing corrector consults as a
//! LOWEST-priority fuzzy tier, after the user dictionary and builtin seeds.
//!
//! Packs are OFF by default; each is toggled independently in Settings
//! (`Settings::enabled_packs`). Data ported from the reference
//! implementation's `Resources/Packs/*.json` (tech, medical, legal, brands,
//! names) — canonical spellings and alias lists are kept verbatim.

/// One vocabulary pack.
pub struct VocabPack {
    /// Stable id: "tech" | "medical" | "legal" | "brands" | "names".
    pub id: &'static str,
    /// Display name.
    pub name: &'static str,
    /// One-line description for the UI.
    pub description: &'static str,
    /// canonical -> known mis-hearings.
    pub terms: &'static [(&'static str, &'static [&'static str])],
}

/// Number of canonical terms in a pack (for the UI's term count).
impl VocabPack {
    pub fn term_count(&self) -> usize {
        self.terms.len()
    }
}

