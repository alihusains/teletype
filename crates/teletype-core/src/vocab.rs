/// Finds a pack by id.
pub fn find(id: &str) -> Option<&'static VocabPack> {
    PACKS.iter().find(|p| p.id == id)
}

/// All built-in packs, in display order.
pub fn all() -> &'static [VocabPack] {
    PACKS
}

/// One flattened pack term for the correction tier (lowercased).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PackTerm {
    /// Canonical spelling (lowercased for matching; the original casing is
    /// not preserved — pack terms are common nouns/brand spellings).
    pub canonical: String,
    /// A known mis-hearing alias (lowercased).
    pub alias: String,
}

/// Flattens the enabled packs into (canonical, alias) pairs for the
/// correction tier. Precompute once per dictation, not per token.
pub fn terms_for(enabled_ids: &[String]) -> Vec<PackTerm> {
    let mut out = Vec::new();
    for p in PACKS.iter().filter(|p| enabled_ids.iter().any(|id| *id == p.id)) {
        for (canonical, aliases) in p.terms {
            let c = canonical.to_lowercase();
            for a in *aliases {
                let alias = a.to_lowercase();
                out.push(PackTerm {
                    canonical: c.clone(),
                    alias,
                });
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn find_returns_each_pack_and_none_for_unknown() {
        assert_eq!(find("tech").map(|p| p.name), Some("Technology"));
        assert_eq!(find("medical").map(|p| p.name), Some("Medical"));
        assert_eq!(find("legal").map(|p| p.name), Some("Legal"));
        assert_eq!(find("brands").map(|p| p.name), Some("Brands"));
        assert_eq!(find("names").map(|p| p.name), Some("Names"));
        assert!(find("nope").is_none());
        assert_eq!(all().len(), 5);
    }

    #[test]
    fn terms_for_flattens_only_enabled_packs_lowercased() {
        let terms = terms_for(&["tech".to_string()]);
        assert!(!terms.is_empty());
        assert!(terms.iter().all(|t| t.canonical == t.canonical.to_lowercase()));
        assert!(terms.iter().all(|t| t.alias == t.alias.to_lowercase()));
        // "cherrypick" -> "cherapak" must be present (reference data).
        assert!(terms.iter().any(|t| t.canonical == "cherrypick" && t.alias == "cherapak"));
        // Disabling everything yields no terms.
        assert!(terms_for(&[]).is_empty());
        // Unknown ids are ignored.
        assert!(terms_for(&["nope".to_string()]).is_empty());
        // Two packs combine.
        let two = terms_for(&["tech".to_string(), "legal".to_string()]);
        assert!(two.len() > terms.len() || two.len() > terms_for(&["legal".to_string()]).len());
    }
}
