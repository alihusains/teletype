//! NeMo Parakeet TDT backend via sherpa-onnx (plan §3.3, P3-D).
//!
//! This is the Windows default engine: the same Parakeet TDT 0.6B models the
//! macOS ggml backend runs, served by sherpa-onnx's `OfflineRecognizer`
//! (transducer, `greedy_search`) on CPU. `sherpa-onnx` links the prebuilt
//! ONNX Runtime statically and ships per-platform prebuilt libraries for its
//! `-sys` crate, so no C toolchain is needed on any host.
//!
//! ## Model layout
//!
//! `load` takes the extracted model directory (the app's `models/` folder
//! after the catalog's `sherpa-onnx-nemo-parakeet-tdt-0.6b-v{2,3}-int8`
//! archive is unpacked). Inside it we expect the standard sherpa-onnx
//! release layout, auto-detected per model family:
//!
//! - v3 (multilingual): `encoder.int8.onnx`, `decoder.int8.onnx`,
//!   `joiner.int8.onnx`, `tokens.txt`
//! - v2 (English): `encoder-epoch-99-avg-16.int8.onnx`,
//!   `decoder-epoch-99-avg-16.onnx`, `joiner-epoch-99-avg-16.int8.onnx`,
//!   `tokens.txt`
//!
//! ## Hotwords (P3.6 spike — documented, not enabled)
//!
//! sherpa-onnx hotwords require `modified_beam_search` (not
//! `greedy_search`) plus `modeling_unit = "bpe"` and a `bpe_vocab` file
//! generated by sentencepiece from the model's `bpe.model`. The published
//! sherpa-onnx Parakeet TDT archives do **not** ship `bpe.model` or a
//! sentencepiece vocab, and NeMo TDT offline + hotwords is not documented
//! by k2-fsa (only transducer models in general). Enabling therefore needs
//! (a) exporting the BPE vocab from the NeMo tokenizer and (b) the
//! Earnings-22-vocab bake-off with real weights; the acceptance bar is
//! recall +10 pts with no WER regression at `hotwords_score` 1.5. Until
//! that lands, boosting for this engine is the post-ASR phonetic rescoring
//! of P3.7 (see plan §14 risk row "sherpa-hotwords").
//!
//! ## VAD
//!
//! Per plan §3.3 the default VAD stays `silero-vad-pure`; sherpa's
//! `VoiceActivityDetector` was not measured (the comparison requires a
//! benchmark harness on the CI box) and nothing here depends on it.

use std::path::{Path, PathBuf};

use crate::{BoostTerm, SpeechError, SpeechProvider, Transcript};

/// The NeMo Parakeet TDT 0.6B v3 int8 transducer (multilingual).
pub const SHERPA_V3: &str = "sherpa-parakeet-v3-int8";
/// The NeMo Parakeet TDT 0.6B v2 int8 transducer (English only).
pub const SHERPA_V2: &str = "sherpa-parakeet-v2-int8";

/// Model families and their transducer file names.
///
/// Both published int8 archives (v2 and v3) ship the same file names —
/// verified against the Hugging Face repos
/// `csukuangfj/sherpa-onnx-nemo-parakeet-tdt-0.6b-v{2,3}-int8`
/// (`encoder.int8.onnx`, `decoder.int8.onnx`, `joiner.int8.onnx`,
/// `tokens.txt`) — so one layout serves both; only the multilingual
/// coverage differs.
const MODEL_FILES: &[&str] = &[
    "encoder.int8.onnx",
    "decoder.int8.onnx",
    "joiner.int8.onnx",
    "tokens.txt",
];

/// `num_threads` per plan §3.3: at most 4, at least 1.
fn recognizer_threads() -> i32 {
    std::thread::available_parallelism()
        .map(|n| n.get() as i32)
        .unwrap_or(4)
        .clamp(1, 4)
}

/// NeMo Parakeet TDT via sherpa-onnx.
///
/// `model` selects the transducer family (see [`SHERPA_V3`] / [`SHERPA_V2`]);
/// the recognizer is created in [`SpeechProvider::load`] and dropped in
/// [`SpeechProvider::unload`]. Transcription is synchronous and blocking —
/// call it from a worker thread, as with every other provider.
pub struct SherpaParakeetProvider {
    model: &'static str,
    recognizer: Option<sherpa_onnx::OfflineRecognizer>,
}

impl std::fmt::Debug for SherpaParakeetProvider {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        // `OfflineRecognizer` is not `Debug`; report only what matters.
        f.debug_struct("SherpaParakeetProvider")
            .field("model", &self.model)
            .field("loaded", &self.recognizer.is_some())
            .finish()
    }
}

impl SherpaParakeetProvider {
    /// Create an unloaded provider for `model` (one of [`SHERPA_V3`] /
    /// [`SHERPA_V2`]). Returns `None` for unknown ids so a catalog typo
    /// fails at construction, not at `load`.
    pub fn new(model: &str) -> Option<Self> {
        let model: &'static str = match model {
            m if m == SHERPA_V3 => SHERPA_V3,
            m if m == SHERPA_V2 => SHERPA_V2,
            _ => return None,
        };
        Some(Self {
            model,
            recognizer: None,
        })
    }

    /// The model family this provider was created for.
    pub fn model(&self) -> &'static str {
        self.model
    }

    /// Build the recognizer config for `dir`. `hotwords` is `None` by
    /// default (see the module docs for why); passing `Some` switches to
    /// `modified_beam_search` as sherpa's hotwords docs require.
    pub fn config_for(
        dir: &Path,
        hotwords: Option<(&Path, f32)>,
    ) -> Result<sherpa_onnx::OfflineRecognizerConfig, SpeechError> {
        let mut paths: Vec<PathBuf> = Vec::with_capacity(MODEL_FILES.len());
        for name in MODEL_FILES {
            let path = dir.join(name);
            if !path.is_file() {
                return Err(SpeechError::ModelLoad(format!(
                    "sherpa-onnx model file missing: {}",
                    path.display()
                )));
            }
            paths.push(path);
        }
        let join = |i: usize| paths[i].to_string_lossy().into_owned();

        let mut config = sherpa_onnx::OfflineRecognizerConfig::default();
        config.model_config.transducer = sherpa_onnx::OfflineTransducerModelConfig {
            encoder: Some(join(0)),
            decoder: Some(join(1)),
            joiner: Some(join(2)),
        };
        config.model_config.tokens = Some(join(3));
        config.model_config.model_type = Some("nemo_transducer".into());
        config.model_config.num_threads = recognizer_threads();
        config.decoding_method = Some(
            if hotwords.is_some() {
                "modified_beam_search"
            } else {
                "greedy_search"
            }
            .into(),
        );
        if let Some((file, score)) = hotwords {
            config.hotwords_file = Some(file.to_string_lossy().into_owned());
            config.hotwords_score = score;
            // sherpa tokenizes hotwords with sentencepiece BPE; the Parakeet
            // TDT models are BPE-modeled. The vocab file itself is the piece
            // the published archives do not ship (see module docs).
            config.model_config.modeling_unit = Some("bpe".into());
            if dir.join("bpe_vocab.txt").is_file() {
                config.model_config.bpe_vocab =
                    Some(dir.join("bpe_vocab.txt").to_string_lossy().into_owned());
            }
        }
        Ok(config)
    }
}

impl SpeechProvider for SherpaParakeetProvider {
    fn load(&mut self, path: &Path) -> Result<(), SpeechError> {
        if self.is_loaded() {
            return Ok(());
        }
        let config = Self::config_for(path, None)?;
        let recognizer = sherpa_onnx::OfflineRecognizer::create(&config).ok_or_else(|| {
            SpeechError::ModelLoad(format!(
                "sherpa-onnx failed to create the {} recognizer (model directory: {})",
                self.model,
                path.display()
            ))
        })?;
        self.recognizer = Some(recognizer);
        Ok(())
    }

    fn unload(&mut self) {
        self.recognizer = None;
    }

    fn is_loaded(&self) -> bool {
        self.recognizer.is_some()
    }

    fn transcribe(&mut self, samples: &[f32], _language: &str) -> Result<String, SpeechError> {
        let recognizer = self.recognizer.as_ref().ok_or(SpeechError::NoModel)?;
        if samples.is_empty() {
            return Err(SpeechError::NoSpeech);
        }
        let stream = recognizer.create_stream();
        stream.accept_waveform(16_000, samples);
        recognizer.decode(&stream);
        let result = stream
            .get_result()
            .ok_or_else(|| SpeechError::Transcribe("sherpa-onnx returned no result".into()))?;
        let text = result.text.trim().to_string();
        if text.is_empty() {
            Err(SpeechError::NoSpeech)
        } else {
            Ok(text)
        }
    }

    /// sherpa reports per-token timestamps/durations (seconds) for the
    /// transducer; we map them to words. Tokens are BPE pieces, so a word is
    /// a run of consecutive tokens; sherpa exposes no per-word confidence,
    /// so words carry the neutral 1.0 (P3.7's rescoring treats a uniform
    /// confidence as "no signal" rather than "certain").
    fn transcribe_detailed(
        &mut self,
        samples: &[f32],
        _language: &str,
    ) -> Result<Transcript, SpeechError> {
        let recognizer = self.recognizer.as_ref().ok_or(SpeechError::NoModel)?;
        if samples.is_empty() {
            return Err(SpeechError::NoSpeech);
        }
        let stream = recognizer.create_stream();
        stream.accept_waveform(16_000, samples);
        recognizer.decode(&stream);
        let result = stream
            .get_result()
            .ok_or_else(|| SpeechError::Transcribe("sherpa-onnx returned no result".into()))?;
        let text = result.text.trim().to_string();
        if text.is_empty() {
            return Err(SpeechError::NoSpeech);
        }

        let words = match (&result.timestamps, &result.durations) {
            (Some(ts), Some(durs)) if ts.len() == result.tokens.len() && ts.len() == durs.len() => {
                crate::group_token_timings(&result.tokens, ts, durs)
            }
            _ => Vec::new(),
        };

        Ok(Transcript {
            text,
            words,
            confidence: 1.0,
            language: None,
        })
    }

    /// Native boosting is not enabled (see the module docs, P3.6 spike).
    /// Storing terms is a no-op that keeps the pipeline uniform; P3.7's
    /// post-ASR rescoring is what actually boosts this engine.
    fn set_boost_terms(&mut self, _terms: &[BoostTerm]) -> Result<(), SpeechError> {
        Ok(())
    }

    /// Word timings are real (token timestamps); native boosting is off.
    fn capabilities(&self) -> crate::ModelCapabilities {
        crate::ModelCapabilities {
            native_boost: false,
            word_timings: true,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unknown_model_ids_are_rejected_at_construction() {
        assert!(SherpaParakeetProvider::new("no-such-model").is_none());
        assert!(SherpaParakeetProvider::new("").is_none());
        let v3 = SherpaParakeetProvider::new(SHERPA_V3).expect("v3 is a known family");
        assert_eq!(v3.model(), SHERPA_V3);
        assert!(!v3.is_loaded());
    }

    #[test]
    fn missing_model_files_are_a_load_error() {
        let mut provider = SherpaParakeetProvider::new(SHERPA_V3).unwrap();
        let dir = std::env::temp_dir().join("teletype-sherpa-missing-test");
        let _ = std::fs::create_dir_all(&dir);
        let error = provider.load(&dir).expect_err("empty dir must fail");
        match error {
            SpeechError::ModelLoad(message) => {
                assert!(message.contains("missing"), "got: {message}");
            }
            other => panic!("wrong error variant: {other:?}"),
        }
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn transcribe_without_load_is_no_model() {
        let mut provider = SherpaParakeetProvider::new(SHERPA_V2).unwrap();
        let error = provider
            .transcribe(&[0.0; 160], "en")
            .expect_err("unloaded provider must refuse");
        assert!(matches!(error, SpeechError::NoModel));
        let error = provider
            .transcribe_detailed(&[0.0; 160], "en")
            .expect_err("unloaded provider must refuse");
        assert!(matches!(error, SpeechError::NoModel));
    }

    #[test]
    fn empty_audio_is_no_model_before_load() {
        // An unloaded provider refuses before it can classify the audio.
        let mut provider = SherpaParakeetProvider::new(SHERPA_V2).unwrap();
        let error = provider
            .transcribe(&[], "en")
            .expect_err("unloaded provider must refuse");
        assert!(matches!(error, SpeechError::NoModel));
    }

    #[test]
    fn boost_terms_are_accepted_without_native_support() {
        let mut provider = SherpaParakeetProvider::new(SHERPA_V2).unwrap();
        provider
            .set_boost_terms(&[BoostTerm {
                text: "Siobhan".into(),
                aliases: vec!["shivon".into()],
                weight: 1.0,
            }])
            .expect("no-op boost must succeed");
        assert!(!provider.capabilities().native_boost);
        assert!(provider.capabilities().word_timings);
    }

    /// End-to-end run against real weights. Disabled unless
    /// `TELETYPE_SHERPA_MODELS` points at an extracted model directory
    /// (one of the catalog's sherpa-onnx Parakeet archives unpacked);
    /// `TELETYPE_SHERPA_MODEL` selects `sherpa-parakeet-v2-int8` (default)
    /// or `sherpa-parakeet-v3-int8`. Speaks a sentence with macOS `say`
    /// when available; otherwise a silence smoke check.
    #[test]
    fn model_gated_end_to_end_transcription() {
        let Some(dir) = std::env::var_os("TELETYPE_SHERPA_MODELS") else {
            return; // no weights requested on this machine
        };
        let model = match std::env::var("TELETYPE_SHERPA_MODEL").as_deref() {
            Ok("sherpa-parakeet-v3-int8") => SHERPA_V3,
            _ => SHERPA_V2,
        };
        let mut provider = SherpaParakeetProvider::new(model).unwrap();
        provider
            .load(Path::new(&dir))
            .expect("loading sherpa-onnx models must succeed");
        assert!(provider.is_loaded());

        if let Some(samples) = synthesized_speech() {
            let detailed = provider
                .transcribe_detailed(&samples, "en")
                .expect("speech must transcribe without error");
            println!(
                "sherpa e2e: text={:?} words={} sample={:?}",
                detailed.text,
                detailed.words.len(),
                detailed
                    .words
                    .iter()
                    .take(4)
                    .map(|w| &w.text)
                    .collect::<Vec<_>>()
            );
            assert!(
                detailed.text.to_lowercase().contains("teletype")
                    || detailed.text.to_lowercase().contains("parakeet"),
                "expected a distinctive word in {:?}",
                detailed.text
            );
        } else {
            let silence = vec![0.0f32; 16_000];
            match provider.transcribe(&silence, "en") {
                Ok(text) => println!("sherpa e2e (silence): {text:?}"),
                Err(SpeechError::NoSpeech) => println!("sherpa e2e (silence): no speech"),
                Err(e) => panic!("silence must not be a hard error: {e}"),
            }
        }

        provider.unload();
        assert!(!provider.is_loaded());
    }

    /// Speak a sentence with macOS TTS and decode it to 16 kHz mono f32.
    fn synthesized_speech() -> Option<Vec<f32>> {
        use std::process::Command;

        const PHRASE: &str = "Hello Teletype, the local parakeet engine is ready.";
        let workdir = std::env::temp_dir().join("teletype-sherpa-e2e");
        std::fs::create_dir_all(&workdir).ok()?;
        let aiff = workdir.join("phrase.aiff");
        let wav = workdir.join("phrase.wav");

        let spoken = Command::new("say")
            .arg("-o")
            .arg(&aiff)
            .arg(PHRASE)
            .status()
            .ok()?;
        if !spoken.success() {
            return None;
        }
        let converted = Command::new("afconvert")
            .args(["-f", "WAVE", "-d", "LEI16@16000", "-c", "1"])
            .arg(&aiff)
            .arg(&wav)
            .status()
            .ok()?;
        if !converted.success() {
            return None;
        }
        read_wav_pcm16(&wav)
    }

    /// Minimal RIFF/WAVE reader for 16 kHz mono PCM16 (chunk-walking).
    fn read_wav_pcm16(path: &Path) -> Option<Vec<f32>> {
        let bytes = std::fs::read(path).ok()?;
        if bytes.len() < 12 || &bytes[0..4] != b"RIFF" || &bytes[8..12] != b"WAVE" {
            return None;
        }
        let mut offset = 12;
        let mut saw_16k_mono = false;
        while offset + 8 <= bytes.len() {
            let id = &bytes[offset..offset + 4];
            let size = u32::from_le_bytes(bytes[offset + 4..offset + 8].try_into().ok()?) as usize;
            let start = offset + 8;
            if id == b"fmt " && size >= 16 {
                let format = u16::from_le_bytes(bytes[start..start + 2].try_into().ok()?);
                let channels = u16::from_le_bytes(bytes[start + 2..start + 4].try_into().ok()?);
                let rate = u32::from_le_bytes(bytes[start + 4..start + 8].try_into().ok()?);
                saw_16k_mono = format == 1 && channels == 1 && rate == 16_000;
            }
            if id == b"data" {
                if !saw_16k_mono {
                    return None;
                }
                let end = start.checked_add(size)?.min(bytes.len());
                return Some(
                    bytes[start..end]
                        .chunks_exact(2)
                        .map(|pair| i16::from_le_bytes([pair[0], pair[1]]) as f32 / 32_768.0)
                        .collect(),
                );
            }
            offset = start + size + (size & 1);
        }
        None
    }
}
